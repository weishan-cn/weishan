assert.equal(share.success, true);
assert.equal(share.share.visibility, "PRIVATE");
assert.equal(share.share.authorizedByUser, true);
assert.equal(share.share.automaticPublication, false);
assert.equal(share.share.socialTrackingEnabled, false);
assert.equal(shareApi.createAnonymousKnowledgeShare({ shareId:"x", title:"x", knowledge:{ question:"x", method:"x", analysis:[] }, userConsent:false }).success, false);
assert.deepEqual(JSON.parse(JSON.stringify(patternApi.listDecisionPatterns().map((item) => item.patternId))), ["PRICE_NOT_BEST", "TOTAL_COST", "RISK_REWARD", "LONG_TERM_VALUE"]);
assert.equal(patternApi.findDecisionPattern("PRICE_NOT_BEST").pattern.personalLearningEnabled, false);
assert.equal(patternApi.findDecisionPattern("UNKNOWN").code, "DECISION_PATTERN_NOT_FOUND");
const feedback = feedbackApi.createDecisionFeedback({ response:"HELPFUL", comment:"Clear risk explanation." });
assert.equal(feedback.success, true);
assert.equal(feedback.feedback.trackingEnabled, false);
assert.equal(feedback.feedback.analyticsEnabled, false);
assert.equal(feedback.feedback.profileUseEnabled, false);
const text = JSON.stringify(templateInput); templateApi.createDecisionTemplate(templateInput); assert.equal(JSON.stringify(templateInput), text);
