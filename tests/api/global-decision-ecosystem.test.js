const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.join(__dirname, "../../apps/desktop/src/renderer/core");
const windowRef = {}; windowRef.window = windowRef;
const context = vm.createContext({ window:windowRef, Set, Number, Object, Array, String, Boolean, RegExp, Math });
["globalCommerceInputGuard.js", "globalDecisionTemplate.js", "globalDecisionKnowledgeShare.js", "globalDecisionPattern.js", "globalDecisionFeedback.js"].forEach((file) => vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context));
const templateApi = windowRef.WeishanGlobalDecisionTemplate;
const shareApi = windowRef.WeishanGlobalDecisionKnowledgeShare;
const patternApi = windowRef.WeishanGlobalDecisionPattern;
const feedbackApi = windowRef.WeishanGlobalDecisionFeedback;
const templateInput = { templateId:"hotel-selection-v1", title:"Hotel selection", templateType:"HOTEL_SELECTION", questionStructure:"What matters for this stay?", comparisonDimensions:["total cost", "location"], riskDimensions:["cancellation", "availability"], analysisFramework:["facts", "risks", "alternatives"], authorDisclosure:{ identity:"Verified template contributor", interestDisclosure:"No commercial relationship declared." } };
const template = templateApi.createDecisionTemplate(templateInput);
assert.equal(template.success, true);
assert.equal(template.template.containsPersonalData, false);
assert.equal(template.template.rankingInfluenceEnabled, false);
assert.equal(template.template.providerInfluenceEnabled, false);
assert.equal(templateApi.createDecisionTemplate(Object.assign({}, templateInput, { accountId:"blocked" })).success, false);
